#!/usr/bin/env python3
"""Emit refs.bib from verified registry records, never from memory.

Entries come from refs/verified_refs.json (status ACCEPTED) plus an explicit
override table for works whose evidence is a retrieved full text rather than a
registry title match. Every emitted entry carries a comment naming its evidence.

Usage: python refs/make_bib.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent

SKIP = {
    "mxfont",        # no registry hit; font baselines already covered
    "schneider1990", # Graphics Gems chapter, no registry record retrieved
    "zhangsuen",     # not needed
    "tortured",      # not needed
    "deep_hccr",     # planted probe, expected to fail
    "crnn",         # no recogniser in the line protocol: AR/CR is computed against the
                     # ground-truth transcription, so a CRNN citation would be ornamental
    "fid",           # replaced by an explicit override (see below): the title match
                     # resolved to a title-squatting DOI 10.18034/ajase.v8i1.9
}

# Works verified by retrieving the paper itself (full text or an official
# proceedings/DOI record) rather than by a registry title match. Stored as data
# in refs/overrides.json, not as a code literal, so each record is auditable.
OVERRIDES_PATH = ROOT / 'overrides.json'
OVERRIDES: dict[str, dict] = json.loads(
    OVERRIDES_PATH.read_text(encoding='utf-8')
)['entries']


def esc(s: str) -> str:
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in (("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_")):
        s = s.replace(a, b)
    return s


_ACCENTS = {
    "\u0301": "'", "\u0300": "`", "\u0302": "^", "\u0308": '"',
    "\u0303": "~", "\u0327": "c", "\u030c": "v", "\u030a": "r",
    "\u0304": "=", "\u0328": "k", "\u0307": ".",
}


def latex_ascii(s: str) -> str:
    """Return the name unchanged.

    The manuscript is built with XeLaTeX, which handles UTF-8 names natively.
    An earlier revision converted accents to macros (Rusi\\~{n}ol); IEEEtran's
    .bst name parser then mis-split the surname and printed "R. nol", so the
    conversion is deliberately not applied. Keeping the real Unicode spelling is
    both more accurate and safer for the bibliography style.
    """
    return s


def clean(s: str) -> str:
    """Collapse exotic whitespace (NBSP, thin/hair spaces, BOM) and control
    characters. Diacritics are preserved: the build is XeLaTeX."""
    s = re.sub(r"[\u00a0\u1680\u2000-\u200f\u2028\u2029\u202f\u205f\u3000\ufeff]", " ", s)
    s = "".join(ch for ch in s if ord(ch) >= 32)
    return re.sub(r"\s+", " ", s).strip()


def authors_from(names: list[str]) -> str:
    return " and ".join(latex_ascii(n) for n in names if n)


def main() -> int:
    data = json.loads((ROOT / "verified_refs.json").read_text(encoding="utf-8"))
    seen = {e["key"] for e in data["entries"]}
    out: list[str] = [
        "% refs.bib - generated by refs/make_bib.py from verified registry records.",
        "% Every entry names its evidence on the line above it. Do not edit by hand;",
        "% regenerate, or add an OVERRIDE in make_bib.py with recorded evidence.",
        "",
    ]
    emitted = 0
    for e in data["entries"]:
        key = e["key"]
        if key in SKIP or e.get("status") != "ACCEPTED":
            continue
        if key in OVERRIDES:
            continue
        typ = "article"
        ts = (e.get("type") or "").lower()
        venue = clean(e.get("venue") or "")
        vlow = venue.lower()
        # IEEE/ACM proceedings records are frequently typed journal-article in
        # Crossref, so the venue string is the more reliable signal.
        if any(w in vlow for w in ("conference", "proceedings", "workshop", "symposium")):
            typ = "inproceedings"
        elif "lecture notes" in vlow or "communications in computer" in vlow:
            typ = "incollection"
        elif ts == "book-chapter":
            typ = "incollection"
        elif ts in ("proceedings-article", "paper-conference"):
            typ = "inproceedings"
        elif ts == "preprint":
            typ = "article"
        elif "journal" in ts:
            typ = "article"
        fields = [
            ("author", authors_from(e.get("authors") or [])),
            ("title", "{" + esc(clean(e.get("matched_title") or e["query_title"])) + "}"),
        ]
        if typ in ("inproceedings", "incollection"):
            fields.append(("booktitle", esc(venue)))
        elif e.get("source") == "arxiv":
            fields.append(("journal", f"arXiv preprint arXiv:{(e.get('arxiv_id') or '').split('v')[0]}"))
        else:
            fields.append(("journal", esc(venue)))
        fields.append(("year", str(e.get("year") or "")))
        if e.get("doi"):
            fields.append(("doi", e["doi"]))
        out.append(f"% evidence: {e.get('source')} title match={e.get('score')} "
                   f"query_url={e.get('query_url')} retrieved_at={e.get('retrieved_at')}")
        out.append(f"@{typ}{{{key},")
        for name, val in fields:
            if val:
                out.append(f"  {name} = {{{val}}},")
        out.append("}")
        out.append("")
        emitted += 1

    for key, o in OVERRIDES.items():
        if key not in seen and key not in {c["key"] for c in json.loads((ROOT / "candidates.json").read_text(encoding="utf-8"))["candidates"]}:
            pass
        out.append(f"% evidence: {o['evidence']}")
        btype = "inproceedings" if o["type"] in ("proceedings", "inproceedings") else o["type"]
        out.append(f"@{btype}{{{key},")
        if not o.get("omit_authors"):
            out.append(f"  author = {{{clean(o['author'])}}},")
        out.append(f"  title = {{{clean(o['title'])}}},")
        for f in ("booktitle", "journal"):
            if o.get(f):
                out.append(f"  {f} = {{{clean(o[f])}}},")
        out.append(f"  year = {{{o['year']}}},")
        if o.get("doi"):
            out.append(f"  doi = {{{o['doi']}}},")
        if o.get("note"):
            out.append(f"  note = {{{clean(o['note'])}}},")
        out.append("}")
        out.append("")
        emitted += 1

    (ROOT / "refs.bib").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {emitted} entries to refs/refs.bib")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
